# Run this single line from the RStudio Console before the notebook chunks.
if (!file.exists("workflow.Rmd") || !dir.exists("vendor"))
  stop("Open the workshop folder as your RStudio project first.")
rscript <- file.path(R.home("bin"), if (.Platform$OS.type == "windows") "Rscript.exe" else "Rscript")
message("Checking R packages in a separate process. Please keep RStudio open.")
status <- system2(rscript, "scripts/install_packages.R")
if (status != 0) stop("Package setup did not finish. Check the messages above and retry.")
message("Package check complete. Detecting your operating system and preparing mothur and the data.")

# Detect the operating system, verify resources, and prepare the input files.
manifest <- jsonlite::read_json("resources.json", simplifyVector = TRUE)
system_name <- Sys.info()[["sysname"]]
stopifnot(tolower(R.version$arch) %in% c("aarch64", "arm64", "x86_64", "amd64"))
architecture <- ifelse(tolower(R.version$arch) %in% c("aarch64", "arm64"), "arm64", "x86_64")
asset <- switch(system_name, Darwin = paste0("Mothur.OSX_", architecture, ".zip"), Linux = paste0("Mothur.linux_", architecture, ".noReadline.zip"), Windows = if (architecture == "x86_64") "Mothur.win.zip" else stop("Windows ARM is not supported"), stop("Unsupported operating system"))
stopifnot(digest::digest(file = file.path("vendor", asset), algo = "sha256", serialize = FALSE) == manifest$resources$sha256[match(asset, manifest$resources$name)])
runtime_cache <- tools::R_user_dir("microbiome-workshop", "cache")
dir.create(runtime_cache, recursive = TRUE, showWarnings = FALSE)
runtime_dir <- tempfile("mothur-runtime-", tmpdir = runtime_cache)
dir.create(runtime_dir, recursive = TRUE, showWarnings = FALSE)
utils::unzip(file.path("vendor", asset), exdir = runtime_dir)
mothur <- normalizePath(list.files(runtime_dir, pattern = if (.Platform$OS.type == "windows") "^mothur\\.exe$" else "^mothur$", recursive = TRUE, full.names = TRUE)[1], mustWork = TRUE)
if (.Platform$OS.type != "windows") Sys.chmod(mothur, "0755")
if (.Platform$OS.type != "windows") Sys.chmod(list.files(dirname(mothur), pattern = "^(vsearch|uchime)$", full.names = TRUE), "0755")
Sys.setenv(PATH = paste(dirname(mothur), Sys.getenv("PATH"), sep = .Platform$path.sep))
run_dir <- file.path("runs", paste0("teaching-", format(Sys.time(), "%Y%m%d-%H%M%S")))
dir.create(run_dir, recursive = TRUE)
run_dir <- normalizePath(run_dir, mustWork = TRUE)
stopifnot(digest::digest(file = "vendor/workshop_reads.zip", algo = "sha256", serialize = FALSE) == manifest$workshop_reads_sha256)
utils::unzip("vendor/workshop_reads.zip", exdir = run_dir)
sample_summary <- read.delim(file.path(run_dir, "filtered_fastq", "summary.tsv"))
read_manifest <- data.frame(sample = sample_summary$sample_id, forward = paste0("filtered_fastq/", sample_summary$sample_id, "_R1.fastq.gz"), reverse = paste0("filtered_fastq/", sample_summary$sample_id, "_R2.fastq.gz"))
write.table(read_manifest, file.path(run_dir, "reads.files"), sep = "\t", quote = FALSE, row.names = FALSE, col.names = FALSE)
stopifnot(digest::digest(file = "vendor/silva.bacteria.zip", algo = "sha256", serialize = FALSE) == manifest$resources$sha256[match("silva.bacteria.zip", manifest$resources$name)])
utils::unzip("vendor/silva.bacteria.zip", exdir = run_dir)
stopifnot(file.copy(file.path(run_dir, "silva.bacteria", "silva.bacteria.fasta"), file.path(run_dir, "silva.bacteria.fasta")))
stopifnot(digest::digest(file = "vendor/trainset9_032012.pds.zip", algo = "sha256", serialize = FALSE) == manifest$resources$sha256[match("trainset9_032012.pds.zip", manifest$resources$name)])
utils::unzip("vendor/trainset9_032012.pds.zip", exdir = run_dir)
message("Detected ", system_name, " (", architecture, "); mothur and the data are ready in ", run_dir, ".")
